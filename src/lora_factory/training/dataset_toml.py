"""tomlkit-based sd-scripts train and validation dataset configuration."""

from __future__ import annotations

import math
import random
from collections.abc import Sequence
from pathlib import Path

import tomlkit
from pydantic import BaseModel, ConfigDict

from lora_factory.config.models import TrainingPlan
from lora_factory.util.hashing import sha256_bytes


class DatasetConfigPaths(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    training: Path
    validation: Path | None


def sd_scripts_validation_partition(
    item_ids: Sequence[str],
    *,
    validation_count: int,
    seed: int,
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Mirror the pinned sd-scripts v0.11.1 DreamBooth split exactly.

    sd-scripts sorts image paths, shuffles them with ``random.Random(seed)``, and
    slices the training and validation datasets independently.  Keeping this small
    compatibility function beside the generated TOML lets the manifest record the
    same holdout set that the real trainer will consume.
    """

    if len(set(item_ids)) != len(item_ids):
        raise ValueError("Validation partition input contains duplicate item IDs")
    total = len(item_ids)
    if total == 0 and validation_count == 0:
        return (), ()
    if validation_count < 0 or validation_count >= total:
        raise ValueError("Validation count must be non-negative and leave training items")
    if validation_count == 0:
        return tuple(sorted(item_ids)), ()
    ordered = sorted(item_ids)
    random.Random(seed).shuffle(ordered)  # noqa: S311 - pinned reproducible split algorithm
    validation_fraction = validation_count / total
    training_boundary = math.ceil(total * (1 - validation_fraction))
    validation_boundary = total - round(total * validation_fraction)
    if training_boundary != validation_boundary:
        raise ValueError(
            "Pinned sd-scripts rounding would overlap or omit validation items for "
            f"{validation_count}/{total}"
        )
    return (
        tuple(sorted(ordered[:training_boundary])),
        tuple(sorted(ordered[validation_boundary:])),
    )


def verify_materialized_validation_partition(
    *,
    image_dir: Path,
    expected_training_ids: Sequence[str],
    expected_validation_ids: Sequence[str],
    seed: int,
) -> None:
    """Fail before training when materialized names would yield another holdout set."""

    image_ids = tuple(path.stem for path in image_dir.glob("*.png") if path.is_file())
    native_training, native_validation = sd_scripts_validation_partition(
        image_ids,
        validation_count=len(expected_validation_ids),
        seed=seed,
    )
    if native_training != tuple(sorted(expected_training_ids)):
        raise ValueError("Materialized sd-scripts training partition differs from the run record")
    if native_validation != tuple(sorted(expected_validation_ids)):
        raise ValueError("Materialized sd-scripts validation partition differs from the run record")


def render_dataset_toml(
    *,
    image_dir: Path,
    plan: TrainingPlan,
    validation: bool = False,
    validation_total_count: int | None = None,
) -> str:
    """Render one sd-scripts dataset config with validation only at dataset level."""

    document = tomlkit.document()
    document.add(tomlkit.comment("Generated by LoRA Factory; do not edit during a run."))
    general = tomlkit.table()
    general["caption_extension"] = ".txt"
    general["shuffle_caption"] = False if validation else plan.shuffle_caption
    general["keep_tokens"] = plan.keep_tokens
    document["general"] = general

    datasets = tomlkit.aot()
    dataset = tomlkit.table()
    dataset["resolution"] = plan.resolution
    dataset["batch_size"] = 1 if validation else plan.batch_size
    dataset["enable_bucket"] = plan.enable_bucket
    dataset["bucket_no_upscale"] = plan.bucket_no_upscale
    if not validation and plan.validation_enabled and validation_total_count is not None:
        if plan.validation_image_count <= 0:
            raise ValueError("Validation-enabled plan has no validation image count")
        if plan.validation_image_count >= validation_total_count:
            raise ValueError("Validation split must leave at least one training image")
        dataset["validation_split"] = plan.validation_image_count / validation_total_count
        dataset["validation_seed"] = plan.validation_seed
    subsets = tomlkit.aot()
    subset = tomlkit.table()
    subset["image_dir"] = str(image_dir.resolve(strict=False))
    subset["num_repeats"] = 1 if validation else plan.repeats
    subsets.append(subset)
    dataset["subsets"] = subsets
    datasets.append(dataset)
    document["datasets"] = datasets
    return tomlkit.dumps(document)


def _atomic_write(path: Path, contents: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(contents, encoding="utf-8", newline="\n")
    temporary.replace(path)


def write_attempt_dataset_config(
    *,
    run_directory: Path,
    image_dir: Path,
    plan: TrainingPlan,
    validation_total_count: int | None,
) -> Path:
    """Write an immutable content-addressed TOML for a recovery plan."""

    contents = render_dataset_toml(
        image_dir=image_dir,
        plan=plan,
        validation=False,
        validation_total_count=validation_total_count,
    )
    digest = sha256_bytes(contents.encode("utf-8"))
    path = run_directory / "training-configs" / f"dataset-{digest}.toml"
    if path.is_file():
        if path.read_text(encoding="utf-8") != contents:
            raise RuntimeError(f"Content-addressed dataset config changed unexpectedly: {path}")
        return path
    _atomic_write(path, contents)
    return path


def write_dataset_configs(
    *,
    output_dir: Path,
    training_image_dir: Path,
    validation_image_dir: Path | None,
    plan: TrainingPlan,
    validation_total_count: int | None = None,
) -> DatasetConfigPaths:
    """Write train TOML and, when enabled, an independent validation TOML."""

    if not training_image_dir.is_dir():
        raise ValueError(f"Training image directory does not exist: {training_image_dir}")
    if plan.validation_enabled and (
        validation_image_dir is None or not validation_image_dir.is_dir()
    ):
        raise ValueError("An existing validation image directory is required by this plan")
    if not plan.validation_enabled and validation_image_dir is not None:
        raise ValueError("Validation directory was supplied for a plan with validation disabled")
    training_path = output_dir / "dataset.toml"
    _atomic_write(
        training_path,
        render_dataset_toml(
            image_dir=training_image_dir,
            plan=plan,
            validation=False,
            validation_total_count=validation_total_count,
        ),
    )
    validation_path: Path | None = None
    if plan.validation_enabled:
        if validation_image_dir is None:
            raise ValueError("Validation image directory unexpectedly became unavailable")
        validation_path = output_dir / "validation.toml"
        _atomic_write(
            validation_path,
            render_dataset_toml(image_dir=validation_image_dir, plan=plan, validation=True),
        )
    return DatasetConfigPaths(training=training_path, validation=validation_path)
